-- Ejecutar conectado a planificacion_cursos.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS roles (
  id_rol integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(30) NOT NULL UNIQUE,
  descripcion varchar(150)
);

CREATE TABLE IF NOT EXISTS usuarios (
  id_usuario bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_rol integer NOT NULL REFERENCES roles(id_rol) ON DELETE RESTRICT,
  nombre_completo varchar(150) NOT NULL,
  correo varchar(180) NOT NULL UNIQUE,
  password_hash text NOT NULL,
  activo boolean NOT NULL DEFAULT true,
  fecha_creacion timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS catedraticos (
  id_catedratico bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario bigint UNIQUE REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
  codigo varchar(30) NOT NULL UNIQUE,
  nombre_completo varchar(150) NOT NULL,
  correo varchar(180) UNIQUE,
  telefono varchar(30),
  activo boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS ciclos (
  id_ciclo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero smallint NOT NULL UNIQUE CHECK (numero > 0),
  nombre varchar(80) NOT NULL,
  activo boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS cursos (
  id_curso bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo varchar(30) NOT NULL UNIQUE,
  nombre varchar(150) NOT NULL,
  descripcion text,
  activo boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS pensum (
  id_curso bigint NOT NULL REFERENCES cursos(id_curso) ON DELETE RESTRICT,
  id_ciclo integer NOT NULL REFERENCES ciclos(id_ciclo) ON DELETE RESTRICT,
  obligatorio boolean NOT NULL DEFAULT true,
  PRIMARY KEY (id_curso, id_ciclo)
);

CREATE TABLE IF NOT EXISTS periodos_academicos (
  id_periodo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  anio integer NOT NULL CHECK (anio BETWEEN 2000 AND 2200),
  semestre smallint NOT NULL CHECK (semestre IN (1, 2)),
  fecha_inicio date NOT NULL,
  fecha_fin date NOT NULL,
  estado varchar(20) NOT NULL DEFAULT 'PLANIFICACION'
    CHECK (estado IN ('PLANIFICACION', 'ACTIVO', 'CERRADO')),
  UNIQUE (anio, semestre),
  UNIQUE (id_periodo, anio, semestre),
  CHECK (fecha_inicio < fecha_fin)
);

CREATE TABLE IF NOT EXISTS secciones (
  id_seccion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_periodo bigint NOT NULL REFERENCES periodos_academicos(id_periodo) ON DELETE RESTRICT,
  id_ciclo integer NOT NULL REFERENCES ciclos(id_ciclo) ON DELETE RESTRICT,
  nombre varchar(10) NOT NULL,
  cupo_estimado integer NOT NULL CHECK (cupo_estimado > 0),
  estado varchar(20) NOT NULL DEFAULT 'ACTIVA'
    CHECK (estado IN ('ACTIVA', 'INACTIVA', 'CERRADA')),
  UNIQUE (id_seccion, id_ciclo, id_periodo),
  UNIQUE (id_periodo, id_ciclo, nombre)
);

CREATE TABLE IF NOT EXISTS salones (
  id_salon bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo varchar(30) NOT NULL UNIQUE,
  descripcion varchar(150),
  capacidad integer NOT NULL CHECK (capacidad > 0),
  estado varchar(20) NOT NULL DEFAULT 'DISPONIBLE'
    CHECK (estado IN ('DISPONIBLE', 'MANTENIMIENTO', 'INACTIVO'))
);

CREATE TABLE IF NOT EXISTS planificaciones (
  id_planificacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_periodo bigint NOT NULL UNIQUE REFERENCES periodos_academicos(id_periodo) ON DELETE RESTRICT,
  id_coordinador bigint NOT NULL REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
  estado varchar(25) NOT NULL DEFAULT 'BORRADOR'
    CHECK (estado IN ('BORRADOR', 'PENDIENTE_APROBACION', 'APROBADA', 'RECHAZADA', 'PUBLICADA')),
  fecha_creacion timestamptz NOT NULL DEFAULT now(),
  fecha_envio timestamptz,
  fecha_publicacion timestamptz,
  UNIQUE (id_planificacion, id_periodo),
  CHECK (fecha_envio IS NULL OR fecha_envio >= fecha_creacion),
  CHECK (fecha_publicacion IS NULL OR fecha_publicacion >= fecha_creacion)
);

CREATE TABLE IF NOT EXISTS asignaciones (
  id_asignacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_planificacion bigint NOT NULL,
  id_periodo bigint NOT NULL,
  id_curso bigint NOT NULL,
  id_ciclo integer NOT NULL,
  id_catedratico bigint NOT NULL REFERENCES catedraticos(id_catedratico) ON DELETE RESTRICT,
  id_seccion bigint NOT NULL,
  id_salon bigint NOT NULL REFERENCES salones(id_salon) ON DELETE RESTRICT,
  fecha_creacion timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (id_planificacion, id_periodo)
    REFERENCES planificaciones(id_planificacion, id_periodo) ON DELETE RESTRICT,
  FOREIGN KEY (id_seccion, id_ciclo, id_periodo)
    REFERENCES secciones(id_seccion, id_ciclo, id_periodo) ON DELETE RESTRICT,
  FOREIGN KEY (id_curso, id_ciclo)
    REFERENCES pensum(id_curso, id_ciclo) ON DELETE RESTRICT,
  UNIQUE (id_planificacion, id_curso, id_seccion, id_catedratico)
);

CREATE TABLE IF NOT EXISTS bloques_horarios (
  id_bloque bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_asignacion bigint NOT NULL REFERENCES asignaciones(id_asignacion) ON DELETE RESTRICT,
  dia_semana smallint NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
  hora_inicio time NOT NULL,
  hora_fin time NOT NULL,
  -- Un día ficticio permite usar tsrange para comparar intervalos de hora.
  horario tsrange GENERATED ALWAYS AS (
    tsrange(
      timestamp '2000-01-01' + hora_inicio,
      timestamp '2000-01-01' + hora_fin,
      '[)'
    )
  ) STORED,
  CHECK (hora_inicio < hora_fin),
  UNIQUE (id_asignacion, dia_semana, hora_inicio, hora_fin),
  EXCLUDE USING gist (
    id_asignacion WITH =,
    dia_semana WITH =,
    horario WITH &&
  )
);

-- Las exclusiones que atraviesan tablas se validan en el backend dentro de la
-- misma transacción, porque el período y el catedrático viven en asignaciones.

CREATE TABLE IF NOT EXISTS revisiones_planificacion (
  id_revision bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_planificacion bigint NOT NULL REFERENCES planificaciones(id_planificacion) ON DELETE RESTRICT,
  id_director bigint NOT NULL REFERENCES usuarios(id_usuario) ON DELETE RESTRICT,
  decision varchar(12) NOT NULL CHECK (decision IN ('APROBADA', 'RECHAZADA')),
  motivo_rechazo text,
  fecha_revision timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (decision = 'RECHAZADA' AND length(btrim(coalesce(motivo_rechazo, ''))) >= 5)
    OR (decision = 'APROBADA' AND motivo_rechazo IS NULL)
  )
);

CREATE INDEX IF NOT EXISTS idx_usuarios_rol ON usuarios(id_rol);
CREATE INDEX IF NOT EXISTS idx_cursos_activos ON cursos(activo);
CREATE INDEX IF NOT EXISTS idx_secciones_periodo ON secciones(id_periodo, id_ciclo);
CREATE INDEX IF NOT EXISTS idx_asignaciones_periodo ON asignaciones(id_periodo);
CREATE INDEX IF NOT EXISTS idx_bloques_dia_hora ON bloques_horarios(dia_semana, horario);
CREATE INDEX IF NOT EXISTS idx_revisiones_planificacion ON revisiones_planificacion(id_planificacion, fecha_revision DESC);

-- Vistas estables para el backend y los reportes.
CREATE OR REPLACE VIEW v_horarios AS
SELECT a.id_asignacion, a.id_periodo, pa.anio, pa.semestre,
       a.id_planificacion, a.id_curso, c.codigo AS curso_codigo, c.nombre AS curso_nombre,
       a.id_ciclo, ci.numero AS ciclo_numero, a.id_seccion, s.nombre AS seccion_nombre,
       a.id_catedratico, cat.codigo AS catedratico_codigo,
       cat.nombre_completo AS catedratico_nombre, a.id_salon, sa.codigo AS salon_codigo,
       b.id_bloque, b.dia_semana, b.hora_inicio, b.hora_fin
FROM asignaciones a
JOIN periodos_academicos pa USING (id_periodo)
JOIN cursos c USING (id_curso)
JOIN ciclos ci USING (id_ciclo)
JOIN secciones s USING (id_seccion)
JOIN catedraticos cat USING (id_catedratico)
JOIN salones sa USING (id_salon)
JOIN bloques_horarios b USING (id_asignacion);

CREATE OR REPLACE VIEW v_cursos_asignados AS
SELECT id_asignacion, id_periodo, anio, semestre, id_catedratico,
       catedratico_codigo, catedratico_nombre, id_curso, curso_codigo,
       curso_nombre, id_ciclo, ciclo_numero, id_seccion, seccion_nombre,
       id_salon, salon_codigo
FROM v_horarios
GROUP BY id_asignacion, id_periodo, anio, semestre, id_catedratico,
         catedratico_codigo, catedratico_nombre, id_curso, curso_codigo,
         curso_nombre, id_ciclo, ciclo_numero, id_seccion, seccion_nombre,
         id_salon, salon_codigo;

CREATE OR REPLACE VIEW v_planificaciones_pendientes AS
SELECT pl.id_planificacion, pl.id_periodo, pa.anio, pa.semestre,
       pl.id_coordinador, u.nombre_completo AS coordinador_nombre,
       pl.estado, pl.fecha_creacion, pl.fecha_envio
FROM planificaciones pl
JOIN periodos_academicos pa USING (id_periodo)
JOIN usuarios u ON u.id_usuario = pl.id_coordinador
WHERE pl.estado = 'PENDIENTE_APROBACION';

CREATE OR REPLACE VIEW v_planificaciones_publicadas AS
SELECT pl.id_planificacion, pl.id_periodo, pa.anio, pa.semestre,
       pl.id_coordinador, u.nombre_completo AS coordinador_nombre,
       pl.estado, pl.fecha_publicacion
FROM planificaciones pl
JOIN periodos_academicos pa USING (id_periodo)
JOIN usuarios u ON u.id_usuario = pl.id_coordinador
WHERE pl.estado = 'PUBLICADA';
