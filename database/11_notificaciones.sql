-- Migración 11: notificaciones dirigidas a usuarios.
-- No crea tablas paralelas ni modifica relaciones existentes.
-- Ejecutar conectado a planificacion_cursos:
-- psql -U postgres -h localhost -p 5433 -d planificacion_cursos -f database/11_notificaciones.sql
\set ON_ERROR_STOP on

BEGIN;

CREATE TABLE IF NOT EXISTS notificaciones (
  id_notificacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario bigint NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
  tipo varchar(40) NOT NULL
    CHECK (tipo IN (
      'ASIGNACION_DOCENTE',
      'PLANIFICACION_ENVIADA',
      'PLANIFICACION_APROBADA',
      'PLANIFICACION_RECHAZADA',
      'HORARIO_PUBLICADO'
    )),
  titulo varchar(180) NOT NULL,
  mensaje text NOT NULL,
  id_planificacion bigint NULL REFERENCES planificaciones(id_planificacion) ON DELETE SET NULL,
  leida boolean NOT NULL DEFAULT false,
  fecha_creacion timestamptz NOT NULL DEFAULT now(),
  fecha_lectura timestamptz NULL
);

CREATE INDEX IF NOT EXISTS idx_notificaciones_usuario
  ON notificaciones (id_usuario);

CREATE INDEX IF NOT EXISTS idx_notificaciones_leida
  ON notificaciones (leida);

CREATE INDEX IF NOT EXISTS idx_notificaciones_fecha_creacion
  ON notificaciones (fecha_creacion DESC);

COMMENT ON TABLE notificaciones IS
  'Mensajes de eventos académicos dirigidos a usuarios del sistema';

COMMENT ON COLUMN notificaciones.tipo IS
  'Tipo de evento que originó la notificación';

COMMENT ON COLUMN notificaciones.fecha_lectura IS
  'Momento en que el usuario marcó la notificación como leída';

-- Consultas de verificación.
SELECT column_name, data_type, character_maximum_length,
       is_nullable, column_default
FROM information_schema.columns
WHERE table_schema = 'public'
  AND table_name = 'notificaciones'
ORDER BY ordinal_position;

SELECT conname, pg_get_constraintdef(oid) AS definicion
FROM pg_constraint
WHERE conrelid = 'public.notificaciones'::regclass
ORDER BY conname;

SELECT indexname, indexdef
FROM pg_indexes
WHERE schemaname = 'public'
  AND tablename = 'notificaciones'
ORDER BY indexname;

SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_name = 'notificaciones';

COMMIT;
