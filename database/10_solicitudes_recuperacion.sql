-- Migración 10: solicitudes de recuperación de contraseña.
-- No modifica tablas existentes ni crea relaciones paralelas.
-- Ejecutar conectado a planificacion_cursos:
-- psql -U postgres -h localhost -p 5433 -d planificacion_cursos -f database/10_solicitudes_recuperacion.sql
\set ON_ERROR_STOP on

BEGIN;

CREATE TABLE IF NOT EXISTS solicitudes_recuperacion (
  id_solicitud bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario bigint NULL REFERENCES usuarios(id_usuario) ON DELETE SET NULL,
  correo varchar(180) NOT NULL,
  mensaje varchar(500),
  estado varchar(20) NOT NULL DEFAULT 'PENDIENTE'
    CHECK (estado IN ('PENDIENTE', 'ATENDIDA', 'CANCELADA')),
  fecha_solicitud timestamptz NOT NULL DEFAULT now(),
  fecha_atencion timestamptz NULL,
  id_coordinador bigint NULL REFERENCES usuarios(id_usuario) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_solicitudes_recuperacion_estado
  ON solicitudes_recuperacion (estado);

CREATE INDEX IF NOT EXISTS idx_solicitudes_recuperacion_fecha
  ON solicitudes_recuperacion (fecha_solicitud DESC);

COMMENT ON TABLE solicitudes_recuperacion IS
  'Solicitudes de usuarios para recuperar el acceso a su cuenta';

COMMENT ON COLUMN solicitudes_recuperacion.id_usuario IS
  'Usuario identificado, si el correo corresponde a una cuenta existente';

COMMENT ON COLUMN solicitudes_recuperacion.id_coordinador IS
  'Coordinador que atendió la solicitud, cuando corresponda';

-- Consultas de verificación.
SELECT column_name, data_type, character_maximum_length,
       is_nullable, column_default
FROM information_schema.columns
WHERE table_schema = 'public'
  AND table_name = 'solicitudes_recuperacion'
ORDER BY ordinal_position;

SELECT conname, pg_get_constraintdef(oid) AS definicion
FROM pg_constraint
WHERE conrelid = 'public.solicitudes_recuperacion'::regclass
ORDER BY conname;

SELECT indexname, indexdef
FROM pg_indexes
WHERE schemaname = 'public'
  AND tablename = 'solicitudes_recuperacion'
ORDER BY indexname;

SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_name = 'solicitudes_recuperacion';

COMMIT;
